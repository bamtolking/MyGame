/* Practice (tutorial) mode flow: hints appear and advance; scripted opponent works. */
import { chromium } from 'playwright-core';
const url = process.argv[2] ?? 'http://localhost:5173/';
const browser = await chromium.launch({ executablePath: '/opt/pw-browsers/chromium-1194/chrome-linux/chrome', args: ['--no-sandbox', '--use-gl=swiftshader', '--enable-unsafe-swiftshader'] });
const ctx = await browser.newContext({ viewport: { width: 844, height: 390 }, deviceScaleFactor: 2, isMobile: true, hasTouch: true });
const page = await ctx.newPage();
const errors = [];
page.on('pageerror', (e) => errors.push('pageerror: ' + e.message));
page.on('console', (m) => { if (m.type() === 'error') errors.push('console: ' + m.text()); });
await page.goto(url, { waitUntil: 'load' });
await page.getByText('연습').first().click();
await page.getByText('경기 시작').click();
await page.waitForTimeout(500);
const hint = async () => (await page.locator('.hint').textContent())?.trim();
console.log('hint1:', await hint());
await page.screenshot({ path: 'screenshots/20-practice-hint1.png' });
const cards = page.locator('.ucard'); const cells = page.locator('.cell');
await cards.nth(0).click(); await cells.nth(2 * 8 + 7).click(); await cells.nth(3 * 8 + 7).click();
await cards.nth(1).click(); await cells.nth(2 * 8 + 5).click(); await cells.nth(3 * 8 + 5).click(); await cells.nth(1 * 8 + 5).click();
await page.waitForTimeout(300);
console.log('hint2:', await hint());
await page.getByRole('button', { name: '출격 준비 완료' }).click();
await page.waitForTimeout(4000);
console.log('hint3:', await hint());
await page.screenshot({ path: 'screenshots/21-practice-battle.png' });
// fast forward the sim to ~25s
await page.evaluate(() => { const m = window.lw.match; while (m.s.t < 25) m.step(); });
await page.waitForTimeout(400);
console.log('hint4:', await hint());
await page.getByRole('button', { name: '상대' }).click(); await page.waitForTimeout(400);
console.log('hint5:', await hint());
await page.screenshot({ path: 'screenshots/22-practice-enemy.png' });
await page.locator('.panel .close').click();
await page.getByRole('button', { name: '편성' }).click();
await cards.nth(2).click(); await cells.nth(2 * 8 + 6).click();
await page.waitForTimeout(400);
console.log('hint6:', await hint());
await page.evaluate(() => { const m = window.lw.match; while (m.s.t < 140 && !m.s.result) m.step(); });
await page.waitForTimeout(400);
console.log('hint7:', await hint());
console.log('enemy waves:', await page.evaluate(() => JSON.stringify(window.lw.match.s.players[1].waves.map((w) => w.counts))));
await cards.nth(3).click(); await cells.nth(2 * 8 + 4).click();
await page.waitForTimeout(400);
console.log('hint8:', await hint());
await page.screenshot({ path: 'screenshots/23-practice-hint-final.png' });
console.log('ERRORS:', errors.length ? errors : 'none');
await browser.close();
