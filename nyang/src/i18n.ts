const DICTS: Record<Lang, Dict> = { ko, en };

export function t(key: string, p?: Record<string, string | number>): string {
  let s = DICTS[lang][key] ?? ko[key] ?? key;
  if (p) for (const k in p) s = s.split(`{${k}}`).join(String(p[k]));
  return s;
}

export function catName(i: number): string { return lang === 'ko' ? CATS[i].name : CAT_EN[i][0]; }
