export function modName(m: Modifier): string { return lang === 'ko' ? m.name : (MOD_EN[m.id]?.[0] ?? m.name); }
export function modDesc(m: Modifier): string { return lang === 'ko' ? m.desc : (MOD_EN[m.id]?.[1] ?? m.desc); }
export function fmt(n: number): string { return Math.round(n).toLocaleString(lang === 'ko' ? 'ko-KR' : 'en-US'); }

