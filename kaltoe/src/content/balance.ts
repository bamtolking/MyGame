/** level → level+1 에 필요한 경험치 (설계 근거는 파일 상단 주석) */
function xpToLevel(level: number): number {
  const L = Math.max(1, Math.floor(level));
  const early = 8 + 16 * (L - 1);                      // Lv1~6 빠른 도입부
  const plateau = 90 + 0.75 * L;                       // Lv7~30 평평한 중반
  const late = 0.08 * Math.max(0, L - 30) ** 2;        // Lv31~ 완만한 가속
  return Math.round(Math.min(early, plateau) + late);
}

