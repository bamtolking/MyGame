/** level → level+1 에 필요한 경험치 (설계 근거는 파일 상단 주석) */
function xpToLevel(level: number): number {
  const L = Math.max(1, Math.floor(level));
  const early = 6 + 10 * (L - 1);                      // Lv1~6 빠른 도입부
  const plateau = 52 + 2.4 * L;                        // Lv7~15 완만한 중반
  // Lv16~ 오목한 가속: 봇 실측 경험치 유입(12시 ≈850, 15시 ≈5.2k, 18시 ≈13.9k)을 Lv 15 / 34 / 52에 맞춤
  const k = Math.max(0, L - 15);
  const late = k < 60 ? 15 * k - 0.12 * k * k : 468 + 5 * (k - 60);
  // Lv6부터 12% 가산: 자석 반경 65 상향 후 봇 실측 레벨이 목표보다 2~3 높아 보정
  return Math.round((Math.min(early, plateau) + late) * (L <= 5 ? 1 : 1.12));
}

