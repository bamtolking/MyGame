// Authoring notes (logical px, y down, TILE 40, ground top = row 11):
//  - jellies are the route guide: row 10 = run/slide line, row 9 = standing only (under a row-8 ceiling),
//    single-jump arcs peak at row 6 (the body at the apex covers rows 5–6), air-jump arches peak at rows 2–3,
//    on a platform at row r the line sits in row r-1 (r-2 only while standing).
//  - 'v' in row 9 = slide under it; 'v' in row 8 = low ceiling: run under it standing, do not jump.
//  - tiers [a,b]: a chunk is proven at every tier speed a..b, so dense patterns live in the high tiers only.
import type { ChunkDef } from '../sim/chunk';
import { ROWS } from './physics';

const E = (n: number) => '.'.repeat(n);
const G = (n: number) => '='.repeat(n);

/**
 * Chunk from bottom-aligned ASCII art: the last line is the ground row and sets the width; missing top rows
 * are empty and shorter rows are right-padded with '.'. Leading/trailing whitespace on each line is ignored.
 */
function C(id: string, tiers: [number, number], tags: string[], art: string, extra: Partial<ChunkDef> = {}): ChunkDef {
  const lines = art.split('\n').map(s => s.trim()).filter(s => s.length > 0);
  const w = lines[lines.length - 1].length;
  if (lines.length > ROWS) throw new Error(`chunk ${id}: ${lines.length} rows > ${ROWS}`);
  for (const l of lines) if (l.length > w) throw new Error(`chunk ${id}: row wider than the ground row: ${l}`);
  const rows = [...Array.from({ length: ROWS - lines.length }, () => E(w)), ...lines.map(l => l + E(w - l.length))];
  return { id, tiers, tags, ...extra, rows };
}

